    /** 粗略识别：中文 / 日语 / 韩语 / 英语，识别不了返回 null */
    fun detect(text: String): String? {
        val letters = text.filter { it.isLetter() }
        if (letters.isEmpty()) return null
        fun ratio(vararg s: Character.UnicodeScript) =
            letters.count { Character.UnicodeScript.of(it.code) in s }.toFloat() / letters.length
        val kana = ratio(Character.UnicodeScript.HIRAGANA, Character.UnicodeScript.KATAKANA)
        return when {
            kana > 0.05 -> "日语"
            ratio(Character.UnicodeScript.HANGUL) > 0.5 -> "韩语"
            ratio(Character.UnicodeScript.HAN) > 0.5 -> "中文"
            ratio(Character.UnicodeScript.LATIN) > 0.8 -> "英语"
            else -> null
        }
    }
